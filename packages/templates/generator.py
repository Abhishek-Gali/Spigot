def _render_readme_md(
    contract: ApiContract,
    tool_plan: ToolPlan,
    policy: RuntimePolicy,
    package_slug: str,
) -> str:
    tool_bullets = []
    for op_id in tool_plan.operation_ids:
        t_name = tool_plan.tool_names[op_id]
        t_desc = tool_plan.descriptions.get(op_id, "")
        clean_desc = " ".join(t_desc.splitlines()).strip()
        tool_bullets.append(f"- `{t_name}` (`{op_id}`): {clean_desc}")
    tools_section = "\n".join(tool_bullets) if tool_bullets else "- *(No enabled tools)*"

    return f"""# {contract.id} — Generated MCP Server (`{package_slug}`)

Generated deterministically by **Spigot (DocForge MCP)** (`v{GENERATOR_VERSION}`).

- **Contract ID:** `{contract.id}` (Revision `{contract.revision}`)
- **Contract Canonical SHA-256:** `{contract.canonical_hash}`
- **Tool Plan SHA-256:** `{tool_plan.plan_hash}`
- **Policy Mode:** `{policy.mode}`
- **Network Profile:** `{policy.network_profile}`

## Standalone Execution

This package runs independently of the **Spigot / DocForge MCP** compiler backend,
SQLite database, and local LLM runtime.

1. Copy `.env.example` to `.env` or export the listed environment variables.
2. Run the MCP stdio server:

```bash
python -m {package_slug}.server
```

## Advertised MCP Tools

{tools_section}

## Security & Provenance Notice

- All tool descriptions, paths, and JSON schemas are loaded as inert JSON data from
  `contract.json`, `tool_plan.json`, and `policy.json`.
- Runtime policy enforcement (`{policy.mode}`) and network egress guards
  (`{policy.network_profile}`) execute before any HTTP request is dispatched.
- Credentials resolved from `SPIGOT_CRED_*` environment variables are automatically
  scrubbed from `stderr` traces and structured error envelopes.
"""


