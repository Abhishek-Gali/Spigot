def _build_compatibility_report(
    contract: ApiContract,
    tool_plan: ToolPlan,
    policy: RuntimePolicy,
) -> dict[str, Any]:
    enabled_set = set(tool_plan.operation_ids)
    disabled_ops = [
        {
            "operation_id": op.stable_id,
            "http_method": op.method,
            "relative_path": op.relative_path,
            "semantic_effect": op.semantic_effect,
            "support_status": op.support_status,
            "reason": (
                "blocked_in_contract"
                if op.support_status != "supported"
                else f"excluded_by_plan_or_policy_{policy.mode}"
            ),
        }
        for op in sorted(contract.operations, key=lambda o: o.stable_id)
        if op.stable_id not in enabled_set
    ]
    return {
        "schema_version": "1.0",
        "generator_brand": "Spigot (DocForge MCP)",
        "generator_version": GENERATOR_VERSION,
        "runtime_version": RUNTIME_VERSION,
        "mcp_sdk_version": MCP_SDK_PIN,
        "contract_hash": contract.canonical_hash,
        "plan_hash": tool_plan.plan_hash,
        "policy_hash": policy.compute_policy_hash(),
        "enabled_operation_ids": list(tool_plan.operation_ids),
        "disabled_operations": disabled_ops,
        "capability_matrix": get_capability_matrix_dict(),
    }


def generate_server_package(
    contract: ApiContract,
    tool_plan: ToolPlan,
    policy: RuntimePolicy,
    output_dir: Path,
    *,
    package_slug: str = "spigot_generated_server",
    manifest_id: str | None = None,
    require_freeze_ready: bool = True,
) -> GenerationManifest:
    """Generate a deterministic, standalone MCP server package on disk."""
    if require_freeze_ready:
        ready, blockers = check_contract_freeze_readiness(
            contract, selected_operation_ids=tool_plan.operation_ids
        )
        if not ready:
            codes = ", ".join(f"{b.code}({b.affected_field})" for b in blockers)
            raise ValueError(f"Contract '{contract.id}' is not freeze-ready: {codes}")

    if contract.canonical_hash != tool_plan.contract_hash:
        raise ValueError(
            f"ToolPlan contract_hash ({tool_plan.contract_hash}) does not match "
            f"ApiContract canonical_hash ({contract.canonical_hash})"
        )

    expected_policy_hash = policy.compute_policy_hash()
    if expected_policy_hash != tool_plan.policy_hash:
        raise ValueError(
            f"ToolPlan policy_hash ({tool_plan.policy_hash}) does not match "
            f"RuntimePolicy hash ({expected_policy_hash})"
        )

    safe_slug = sanitize_package_slug(package_slug)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Read runtime engine source and validate AST
    engine_source_path = Path(__file__).resolve().parent.parent / "runtime" / "engine.py"
    engine_source = engine_source_path.read_text(encoding="utf-8")
    ast.parse(engine_source, filename=f"{safe_slug}/runtime_engine.py")

    contract_dict = contract.model_dump(mode="json", by_alias=True)
    artifact_hashes: dict[str, str] = {}

    def _record_file(rel_path: str, raw_bytes: bytes) -> None:
        artifact_hashes[rel_path] = sha256_hex(raw_bytes)

    # 1. Write inert JSON data files
    _record_file(
        "contract.json",
        _write_canonical_json(output_dir / "contract.json", contract_dict),
    )
    _record_file(
        "tool_plan.json",
        _write_canonical_json(
            output_dir / "tool_plan.json", tool_plan.model_dump(mode="json")
        ),
    )
    _record_file(
        "policy.json",
        _write_canonical_json(output_dir / "policy.json", policy.model_dump(mode="json")),
    )
    _record_file(
        "compatibility_report.json",
        _write_canonical_json(
            output_dir / "compatibility_report.json",
            _build_compatibility_report(contract, tool_plan, policy),
        ),
    )

    # 2. Write configuration, docs, and metadata
    _record_file(
        ".env.example",
        _write_lf_text(output_dir / ".env.example", _render_env_example(contract)),
    )
    _record_file(
        "pyproject.toml",
        _write_lf_text(output_dir / "pyproject.toml", _render_pyproject_toml(safe_slug)),
    )
    _record_file(
        "README.md",
        _write_lf_text(
            output_dir / "README.md",
            _render_readme_md(contract, tool_plan, policy, safe_slug),
        ),
    )
    _record_file(
        "LICENSE",
        _write_lf_text(output_dir / "LICENSE", _render_license()),
    )

    # 3. Write Python package modules (AST-verified)
    init_code = '"""Generated standalone MCP server package."""\n'
    ast.parse(init_code, filename=f"{safe_slug}/__init__.py")
    _record_file(
        f"{safe_slug}/__init__.py",
        _write_lf_text(output_dir / safe_slug / "__init__.py", init_code),
    )
    _record_file(
        f"{safe_slug}/runtime_engine.py",
        _write_lf_text(output_dir / safe_slug / "runtime_engine.py", engine_source),
    )
    server_code = _render_server_py(safe_slug, contract.id)
    _record_file(
        f"{safe_slug}/server.py",
        _write_lf_text(output_dir / safe_slug / "server.py", server_code),
    )

    # 4. Write smoke tests (AST-verified)
    smoke_code = _render_smoke_test_py(safe_slug)
    _record_file(
        "tests/test_smoke.py",
        _write_lf_text(output_dir / "tests" / "test_smoke.py", smoke_code),
    )

    # Compute deterministic template and dependency lock hashes
    generator_self_bytes = Path(__file__).resolve().read_bytes().replace(b"\r\n", b"\n")
    engine_bytes = engine_source.replace("\r\n", "\n").encode("utf-8")
    template_hash = sha256_hex(generator_self_bytes + b"\n---\n" + engine_bytes)

    dep_lock_payload = {
        "mcp": MCP_SDK_PIN,
        "httpx": HTTPX_PIN,
        "jsonschema": JSONSCHEMA_PIN,
        "pydantic": PYDANTIC_PIN,
    }
    dependency_lock_hash = sha256_hex(canonical_json_bytes(dep_lock_payload))

    sorted_artifact_hashes = dict(sorted(artifact_hashes.items()))
    effective_manifest_id = manifest_id or f"manifest-{contract.id}-r{contract.revision}"

    manifest = GenerationManifest(
        id=effective_manifest_id,
        artifact_hashes=sorted_artifact_hashes,
        contract_hash=contract.canonical_hash,
        plan_hash=tool_plan.plan_hash,
        generator_version=GENERATOR_VERSION,
        template_hash=template_hash,
        runtime_version=RUNTIME_VERSION,
        dependency_lock_hash=dependency_lock_hash,
    )
    _write_canonical_json(output_dir / "manifest.json", manifest.model_dump(mode="json"))

    # Remove any unmanifested stale files from output_dir
    expected_rel_paths = set(sorted_artifact_hashes.keys()) | {"manifest.json"}
    for existing_file in list(output_dir.rglob("*")):
        if existing_file.is_file():
            rel_posix = existing_file.relative_to(output_dir).as_posix()
            if rel_posix not in expected_rel_paths:
                existing_file.unlink()

    return manifest


def export_reproducible_zip(package_dir: Path, zip_path: Path) -> bytes:
    """Create a byte-for-byte reproducible `.zip` archive from a generated package directory.

    If `manifest.json` is present in `package_dir`, strictly enforces that only manifested
    files (plus `manifest.json`) exist in `package_dir` and that every file matches its
    manifested SHA-256 digest before archiving.
    """
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    all_files = sorted(
        (p for p in package_dir.rglob("*") if p.is_file()),
        key=lambda p: p.relative_to(package_dir).as_posix(),
    )

    manifest_file = package_dir / "manifest.json"
    if manifest_file.exists():
        manifest = GenerationManifest.model_validate_json(
            manifest_file.read_text(encoding="utf-8")
        )
        allowed_paths = set(manifest.artifact_hashes.keys()) | {"manifest.json"}
        actual_paths = {
            p.relative_to(package_dir).as_posix() for p in all_files
        }
        unmanifested = sorted(actual_paths - allowed_paths)
        if unmanifested:
            raise ValueError(
                f"Refusing to export ZIP containing unmanifested files: {unmanifested}"
            )
        missing = sorted(set(manifest.artifact_hashes.keys()) - actual_paths)
        if missing:
            raise ValueError(
                f"Refusing to export ZIP missing manifested files: {missing}"
            )
        for rel_posix, expected_sha in manifest.artifact_hashes.items():
            actual_sha = sha256_hex((package_dir / rel_posix).read_bytes())
            if actual_sha != expected_sha:
                raise ValueError(
                    f"Refusing to export ZIP: hash mismatch for '{rel_posix}'"
                )

    with zipfile.ZipFile(zip_path, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for file_path in all_files:
            rel_posix = file_path.relative_to(package_dir).as_posix()
            info = zipfile.ZipInfo(filename=rel_posix, date_time=FIXED_ZIP_DATETIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3  # Unix attribute format for cross-OS determinism
            info.external_attr = (0o100644 & 0xFFFF) << 16
            zf.writestr(info, file_path.read_bytes())

    return zip_path.read_bytes()
