"""Deterministic MCP Server Generator & Reproducible Exporter (T09 & T12).

Consumes an immutable `ApiContract`, `ToolPlan`, and `RuntimePolicy` to emit a
standalone, self-contained MCP server package and reproducible `.zip` bundle.

Security & Determinism Invariants:
- Templates never invoke local or cloud LLMs or make network calls.
- Untrusted strings (operation names, descriptions, paths, parameter names/schemas)
  are NEVER interpolated into Python source code; they are stored in `contract.json`,
  `tool_plan.json`, and `policy.json` and loaded via `json.loads` at runtime.
- Every generated `.py` file is validated via `ast.parse()` before writing.
- Identical frozen inputs produce byte-for-byte identical files, `manifest_hash`,
  and `.zip` SHA-256 digests (`FR-13`).
"""

from __future__ import annotations

import ast
import json
import re
import zipfile
from pathlib import Path
from typing import Any

from packages.core.contracts import (
    ApiContract,
    GenerationManifest,
    ToolPlan,
    canonical_json_bytes,
    sha256_hex,
)
from packages.core.planning import RuntimePolicy
from packages.core.readiness import check_contract_freeze_readiness
from packages.core.support_registry import get_capability_matrix_dict
from packages.runtime.engine import env_var_for_scheme, env_var_for_server

GENERATOR_VERSION = "0.2.0"
RUNTIME_VERSION = "0.2.0"
MCP_SDK_PIN = "2.3.0"
HTTPX_PIN = "0.28.1"
JSONSCHEMA_PIN = "4.26.0"
PYDANTIC_PIN = "2.14.0"

FIXED_ZIP_DATETIME = (2026, 1, 1, 0, 0, 0)


def sanitize_package_slug(raw_slug: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9_]+", "_", raw_slug.strip()).strip("_").lower()
    if not slug or not slug[0].isalpha():
        slug = f"spigot_{slug}" if slug else "spigot_generated_server"
    return slug


def _write_lf_text(path: Path, content: str) -> bytes:
    normalized = content.replace("\r\n", "\n").replace("\r", "\n")
    if not normalized.endswith("\n"):
        normalized += "\n"
    data = normalized.encode("utf-8")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return data


def _write_canonical_json(path: Path, payload: Any) -> bytes:
    formatted = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False)
    return _write_lf_text(path, formatted)


def _render_server_py(package_slug: str, server_name: str) -> str:
    # Only safe verified identifiers/literals are placed in Python source;
    # all contract/tool descriptions and paths are loaded from JSON files.
    safe_server_name = (
        re.sub(r"[^a-zA-Z0-9_-]+", "-", server_name).strip("-") or "spigot-mcp-server"
    )
    code = f'''"""Standalone MCP stdio server generated by Spigot (DocForge MCP).

This entrypoint loads inert JSON artifacts (`contract.json`, `tool_plan.json`,
`policy.json`) from the package root and delegates execution to the bundled
`runtime_engine` without requiring the Spigot compiler backend or SQLite DB.
"""

from __future__ import annotations

import asyncio
from pathlib import Path

from {package_slug}.runtime_engine import load_engine_from_package_dir

PACKAGE_ROOT = Path(__file__).resolve().parent.parent
SERVER_NAME = {json.dumps(safe_server_name)}
SERVER_VERSION = {json.dumps(RUNTIME_VERSION)}


def create_engine():
    return load_engine_from_package_dir(
        PACKAGE_ROOT,
        server_name=SERVER_NAME,
        server_version=SERVER_VERSION,
    )


def main() -> None:
    engine = create_engine()
    asyncio.run(engine.run_stdio())


if __name__ == "__main__":
    main()
'''
    ast.parse(code, filename=f"{package_slug}/server.py")
    return code


def _render_smoke_test_py(package_slug: str) -> str:
    code = f'''"""Generated offline smoke tests for {package_slug} (Spigot / DocForge MCP)."""

from __future__ import annotations

import asyncio

from {package_slug}.server import create_engine


def test_engine_loads_and_lists_enabled_tools() -> None:
    engine = create_engine()
    tools = engine.list_tools_sync()
    assert len(tools) == len(engine.enabled_tool_names)
    for tool in tools:
        assert tool.name
        assert isinstance(tool.inputSchema, dict)


def test_unknown_tool_is_rejected_without_network() -> None:
    engine = create_engine()
    res = asyncio.run(engine.call_tool_async("__nonexistent_tool__", {{}}))
    assert res.is_error is True
    assert "POLICY_DENIED" in res.content[0].text
'''
    ast.parse(code, filename="tests/test_smoke.py")
    return code


def _render_env_example(contract: ApiContract) -> str:
    lines = [
        "# Spigot (DocForge MCP) Generated Server Runtime Environment Variables",
        "# Populate secret values in your local environment before running.",
        "# NEVER commit actual credentials to version control.",
        "",
    ]
    for srv in sorted(contract.servers, key=lambda s: s.server_id):
        env_name = env_var_for_server(srv.server_id)
        lines.append(
            f"# Override base URL for server '{srv.server_id}' (default: {srv.base_url})"
        )
        lines.append(f"{env_name}=")
    for scheme in sorted(contract.security_schemes, key=lambda s: s.scheme_id):
        env_name = env_var_for_scheme(scheme.scheme_id)
        lines.append(
            f"# Credential for security scheme '{scheme.scheme_id}' (type: {scheme.type})"
        )
        lines.append(f"{env_name}=")
    lines.extend(
        [
            "",
            "# Action Approval Authority (required when policy mode is 'approval_required')",
            "# Shared HMAC secret (>=16 chars) or workspace key file provisioned by Spigot Local API",
            "SPIGOT_APPROVAL_SECRET=",
            "SPIGOT_APPROVAL_SECRET_FILE=.spigot/workspace/approval_authority.key",
            "# Persistent SQLite ledger path for atomic single-use nonce replay protection",
            "SPIGOT_APPROVAL_LEDGER_PATH=.spigot/consumed_approvals.sqlite3",
            "# Per-invocation single-use owner approval token JSON (when executing an approved write)",
            "SPIGOT_ACTION_APPROVAL_TOKEN=",
        ]
    )
    return "\n".join(lines) + "\n"


